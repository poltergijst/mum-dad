export type LanguageCode = 'en' | 'es' | 'fr' | 'de' | 'it' | 'pt' | 'nl' | 'tr';

export interface LanguageOption {
  code: LanguageCode;
  label: string;
  speechCode: string;
}

export const LANGUAGES: LanguageOption[] = [
  { code: 'en', label: 'English', speechCode: 'en-US' },
  { code: 'es', label: 'Español', speechCode: 'es-ES' },
  { code: 'fr', label: 'Français', speechCode: 'fr-FR' },
  { code: 'de', label: 'Deutsch', speechCode: 'de-DE' },
  { code: 'it', label: 'Italiano', speechCode: 'it-IT' },
  { code: 'pt', label: 'Português', speechCode: 'pt-BR' },
  { code: 'nl', label: 'Nederlands', speechCode: 'nl-NL' },
  { code: 'tr', label: 'Türkçe', speechCode: 'tr-TR' },
];

export const DEFAULT_LANGUAGE: LanguageCode = 'en';

export function getSpeechCode(lang: LanguageCode): string {
  return LANGUAGES.find(l => l.code === lang)?.speechCode ?? 'en-US';
}

